/**
 * Fingerprints of the three Apps Script projects, shared by
 * scripts/apps-script/cli.mjs (`npm run gas:*`) and the tests.
 *
 * A project's fingerprint is a hash of every file `clasp push` deploys
 * from its folder (top-level .gs files and appsscript.json), except
 * Version.gs, which holds the fingerprint itself. Any code change -
 * including deleting a file - changes it.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const SCRIPTS_ROOT = path.join(REPO_ROOT, "scripts/GoogleAppsScriptsCode");
export const GENERATED_TS = path.join(REPO_ROOT, "server/generated/appsScriptVersions.ts");
export const VERSION_FILE = "Version.gs";

/** Folder name -> what the app calls it and the server setting holding its Script ID. */
export const PROJECTS = {
  BidManagementSpreadsheet: { label: "Bid Management", envVar: "SCRIPT_ID_BID_MANAGEMENT" },
  ItemsSpreadsheet: { label: "Item Entry", envVar: "SCRIPT_ID_ITEM_ENTRY" },
  TicketsSpreadsheet: { label: "Tickets", envVar: "SCRIPT_ID_TICKETS" },
};

/** The files clasp pushes from a project folder, sorted, without Version.gs. */
export function deployedFiles(project) {
  const dir = path.join(SCRIPTS_ROOT, project);
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && (e.name.endsWith(".gs") || e.name === "appsscript.json") && e.name !== VERSION_FILE)
    .map((e) => e.name)
    .sort();
}

/** Line endings are normalized so a Windows checkout gets the same fingerprint. */
export function fingerprint(project) {
  const hash = crypto.createHash("sha256");
  for (const name of deployedFiles(project)) {
    const source = fs.readFileSync(path.join(SCRIPTS_ROOT, project, name), "utf8").replace(/\r\n/g, "\n");
    hash.update(name).update("\0").update(source).update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

export function versionFileSource(version) {
  return `/**
 * Generated by \`npm run gas:stamp\` - do not edit by hand.
 *
 * SCRIPT_VERSION is a fingerprint of every other file in this project
 * (scripts/apps-script/fingerprint.mjs). The app's Settings page calls
 * apiGetVersion and compares it with the fingerprint the app was built
 * with, to show whether the live script matches the repo.
 */
const SCRIPT_VERSION = '${version}';

function apiGetVersion () {
    return { success: true, version: SCRIPT_VERSION };
}
`;
}

/** The fingerprint written in a project's Version.gs, or null if missing. */
export function stampedVersion(project) {
  const file = path.join(SCRIPTS_ROOT, project, VERSION_FILE);
  if (!fs.existsSync(file)) return null;
  const match = fs.readFileSync(file, "utf8").match(/const SCRIPT_VERSION = '([0-9a-f]+)'/);
  return match ? match[1] : null;
}

export function generatedTsSource(versions) {
  const lines = Object.entries(versions).map(([project, version]) => `  ${project}: "${version}",`);
  return `// Generated by \`npm run gas:stamp\` - do not edit by hand.
// The fingerprint each Apps Script project's Version.gs should report
// (scripts/apps-script/fingerprint.mjs); see server/routes/appsScriptRoutes.ts.
export const EXPECTED_APPS_SCRIPT_VERSIONS = {
${lines.join("\n")}
} as const;
`;
}
